// Декодирует UTF-8 символ, возвращает Unicode code point
// Возвращает количество прочитанных байт через *len
static inline uint32_t utf8_decode(const char *str, int *len)
{
    uint8_t c = (uint8_t)str[0];
    
    if (c < 0x80) {
        *len = 1;
        return c;
    }
    else if ((c & 0xE0) == 0xC0) {
        *len = 2;
        return ((c & 0x1F) << 6) | (str[1] & 0x3F);
    }
    else if ((c & 0xF0) == 0xE0) {
        *len = 3;
        return ((c & 0x0F) << 12) | ((str[1] & 0x3F) << 6) | (str[2] & 0x3F);
    }
    *len = 1;
    return '?';
}

// Возвращает указатель на глиф для символа
static inline const uint8_t* get_glyph(uint32_t codepoint)
{
    // ASCII
    if (codepoint >= 32 && codepoint <= 126) {
        return &font5x7_ascii[(codepoint - 32) * 5];
    }
    
    // Кириллица заглавные А-Я (U+0410 - U+042F)
    if (codepoint >= 0x410 && codepoint <= 0x42F) {
        return &font5x7_cyr[(codepoint - 0x410) * 5];
    }
    
    // Кириллица строчные а-я (U+0430 - U+044F)
    if (codepoint >= 0x430 && codepoint <= 0x044F) {
        return &font5x7_cyr[(32 + codepoint - 0x430) * 5];
    }
    
    // Ё (U+0401)
    if (codepoint == 0x401) {
        return &font5x7_cyr[64 * 5];
    }
    
    // ё (U+0451)
    if (codepoint == 0x451) {
        return &font5x7_cyr[65 * 5];
    }
    
    // Неизвестный символ - вернуть '?'
    return &font5x7_ascii[('?' - 32) * 5];
}

